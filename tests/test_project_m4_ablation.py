def test_m4_writer_context_pair_same_script_permissions_oracle_and_restorable_original(tmp_path):
    from corecoder.context import estimate_tokens
    from corecoder.tools.read import ReadFileTool
    from corecoder.workflow import workspace_revision
    from researchcoder.context import AccessScope, EvidenceStore
    from researchcoder.context.compression import validate_pairs
    from researchcoder.context.policy import ContextPolicy

    arms = {}
    for strategy in ("original", "evidence"):
        root = tmp_path / strategy
        root.mkdir()
        source, task, checks = fixture(root, long_source=True)
        target = root / "trial"
        context = ContextPolicy(strategy=strategy, role="repair", allow_recovery=True,
                                coding_source_mode="observed-source-v1")
        result = ProjectEvaluationRunner().run(target, task, source, checks["public"], checks["f2p"], checks["p2p"],
            writer(), policy=policy(feedback=0), writer_context_policy=context)
        raw, io, requests = archived(target)
        assert_integrity(result, raw, io, requests, source, task, checks)
        assert result["end_to_end_success"] and result["fail_to_pass"] and result["pass_to_pass"]
        assert len(requests) == result["model_requests"] == 3
        assert recompute(target) == result
        outputs = [io.read_json(ArtifactRef.from_dict(ref)) for ref in raw["attempt_results"][0]["outputs"]]
        context_receipts = [value for value in outputs if "context_catalog" in value]
        assert len(context_receipts) == 1
        receipt = context_receipts[0]
        assert receipt["policy"] == context.to_dict()
        assert len(receipt["compression_receipts"]) == len(requests)
        reads = receipt["coding_sources"]["reads"]
        assert len(reads) == 1 and reads[0]["source_path"] == "loader.py"
        binding = reads[0]
        assert binding["file_sha256"] == _sha(source / "loader.py")
        assert binding["full_manifest_sha256"] == task.manifest.digest
        assert receipt["coding_sources"]["current_full_manifest_sha256"] == capture_manifest(target / "candidate").digest
        store = EvidenceStore.load(io, ArtifactRef.from_dict(receipt["context_catalog"]), raw["job_id"])
        docs = {doc.document_id: doc for doc in store.catalog.documents}
        rendered = docs[binding["rendered_document_id"]]
        observed_source = docs[binding["document_id"]]
        scope = AccessScope(job_id=raw["job_id"], task_id=raw["attempt_results"][0]["task_id"],
            attempt_id=raw["attempt_results"][0]["attempt_id"], workspace_revision=workspace_revision(target / "candidate"),
            allow_historical=True)
        recovered = store.restore_document(rendered, scope)
        assert recovered["content"] == ReadFileTool().execute(str(source / "loader.py"))
        assert recovered["original_sha256"] == binding["rendered_sha256"]
        assert hashlib.sha256(recovered["content"].encode()).hexdigest() == binding["rendered_sha256"]
        assert not recovered["current_eligible"] and recovered["classification"] == "historical_observation"
        page = store.restore_document(observed_source, scope)
        assert page["original_sha256"] == binding["source_artifact_sha256"]
        assert WRONG in page["content"] and CORRECT not in page["content"]
        with pytest.raises(ValueError):
            store.restore_document(rendered, replace(scope, allow_historical=False))
        with pytest.raises(ValueError):
            store.restore_document(rendered, replace(scope, job_id="foreign-job"))
        total_estimate = 0
        schemas = []
        for request in requests:
            messages = request["request"]["messages"]
            tools = request["request"]["tools"]
            validate_pairs(messages)
            total_estimate += estimate_tokens(messages) + len(json.dumps(tools, ensure_ascii=False)) // 3
            names = tuple(tool["function"]["name"] for tool in tools)
            assert "restore_context_evidence" in names
            assert set(names) == {"read_file", "edit_file", "restore_context_evidence"}
            schemas.append(tools)
        native = next(value for value in outputs if "baseline_hypothesis" in value)
        tools_run = [event["tool"] for event in native["events"]]
        assert tools_run == ["read_file", "edit_file"]
        traces = [io.read_json(ArtifactRef.from_dict(row["trace"])) for row in raw["records"]]
        assert sum(event["event_type"] == "context.built" for trace in traces for event in trace["events"]) == 3
        # Evidence is evaluated from the admitted request, never inferred from a
        # scripted repair result which is intentionally independent of the view.
        admitted = json.dumps(requests[1]["request"]["messages"], ensure_ascii=False)
        assert "KeyError" in admitted and "loader.py" in admitted
        if strategy == "evidence":
            assert "coding_source" in admitted and "source_index" in admitted
            memories = [json.loads(message["content"].split("\n", 1)[1])
                        for message in requests[1]["request"]["messages"]
                        if (message.get("content") or "").startswith("[Evidence context:")]
            source_cards = [card for memory in memories for card in memory["records"]
                            if card.get("coding_source")]
            assert any(WRONG in line["text"] for card in source_cards for line in card.get("excerpt", []))
        arms[strategy] = dict(result=result, estimate=total_estimate, schemas=schemas,
            tools_run=tools_run, source_sha=task.manifest.digest,
            oracle={name: checks[name].protected_files[0].sha256 for name in checks},
            charged=raw["budget"]["charged"])
    assert arms["original"]["source_sha"] == arms["evidence"]["source_sha"]
    assert arms["original"]["oracle"] == arms["evidence"]["oracle"]
    assert arms["original"]["schemas"] == arms["evidence"]["schemas"]
    assert arms["original"]["tools_run"] == arms["evidence"]["tools_run"]
    assert arms["evidence"]["estimate"] < arms["original"]["estimate"]
    # These 100/20 turn counters are artificial and identical. Only effective
    # request size above supports an offline input-estimation comparison.
    assert arms["original"]["charged"] == arms["evidence"]["charged"]
