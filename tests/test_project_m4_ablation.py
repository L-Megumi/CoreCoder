FIXTURE = Path(__file__).parent / "fixtures" / "project_m4"
SECRET = "PRIVATE_M4_ORACLE_SENTINEL_83adc12b"
WRONG = 'return tuple(record["payload"])'
CORRECT = 'return tuple(record["features"])'
PUBLIC_ONLY = 'return (2, 3)'
ORIGINAL_MESSAGE = "record has no usable feature list"
PARTIAL_MESSAGE = "record loading failed; inspect the declared feature field"
SIMULATED_USAGE = dict(prompt_tokens=100, completion_tokens=20)


def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fixture(tmp_path, *, long_source=False):
    source = tmp_path / "source"
    shutil.copytree(FIXTURE / "buggy", source)
    if long_source:
        loader = (source / "loader.py").read_text()
        # Comments surround, rather than replace, the same real faulty source.
        padding = "".join(f"# unrelated example {i:04d}: immutable record diagnostics\n" for i in range(350))
        (source / "loader.py").write_text(padding + loader + padding, encoding="utf-8")
    public, private = tmp_path / "public_check.py", tmp_path / "private_check.py"
    shutil.copyfile(FIXTURE / "public_check.py", public)
    shutil.copyfile(FIXTURE / "private_check.py", private)
    checks = {}
    expected = {"public": ("public-feature-sum",), "f2p": ("unseen-signed-values", "empty-features"),
                "p2p": ("identity-object", "identity-scalar")}
    for profile in ("public", "f2p", "p2p"):
        checker = public if profile == "public" else private
        argv = (sys.executable, "-I", "-B", str(checker), "{project}")
        if profile != "public":
            argv += (profile,)
        checks[profile] = ProjectCheck(check_id="m4-" + profile, argv_template=argv,
            protected_files=(ProtectedFile(path=str(checker), sha256=_sha(checker)),), timeout_seconds=15,
            receipt=ReceiptSpec(kind="checks_json", origin_field="origin", origin_relative_path="loader.py",
                required_fields=("schema_version", "profile", "origin", "source_sha256", "checks", "passed"),
                exact_fields=(("schema_version", 1), ("profile", profile)), expected_checks=expected[profile],
                digest_field="source_sha256", digest_relative_path="loader.py"))
    reproduction = subprocess.run(checks["public"].command(source).argv, cwd=source,
        capture_output=True, text=True, timeout=15, check=False)
    assert reproduction.returncode == 1
    assert reproduction.stderr.count("Traceback (most recent call last):") == 2
    assert "The above exception was the direct cause" in reproduction.stderr
    assert "KeyError: 'payload'" in reproduction.stderr
    log = reproduction.stderr
    if long_source:
        noise = "INFO unchanged warmup record\n" * 250
        log = noise + log + noise
    task = ProjectRunInput(project_id="m4-two-file-contract", source_revision="fixture-v1",
        manifest=capture_manifest(source), objective=(
            "Repair total_features: sum the public record's features sequence without changing the input. "
            "Preserve load_values ordering and legacy_identity behavior. Inspect both source files as needed."),
        public_log=log, writable_paths=("loader.py", "pipeline.py"))
    return source, task, checks


def call(name, arguments, identity):
    return ScriptedTurn(calls=(ScriptedCall(call_id=identity, name=name,
        arguments_json=json.dumps(arguments)),), **SIMULATED_USAGE)


def writer(kind="correct"):
    turns = [call("read_file", {"file_path": "loader.py"}, "read-loader")]
    if kind != "no_patch":
        turns.append(call("edit_file", dict(file_path="loader.py", old_string=WRONG,
            new_string=PUBLIC_ONLY if kind == "public_only" else CORRECT), "edit-loader"))
    if kind == "regression":
        turns.append(call("edit_file", dict(file_path="loader.py", old_string="return value", new_string="return None"), "break-identity"))
    turns.append(ScriptedTurn(content="The current source was inspected. The independent check determines the outcome.", **SIMULATED_USAGE))
    return ModelSpec(turns=tuple(turns))


def partial_writer():
    # Three completed requests/actions; a fourth request is refused locally.
    return ModelSpec(turns=(
        call("read_file", {"file_path": "pipeline.py"}, "read-pipeline"),
        call("edit_file", dict(file_path="pipeline.py", old_string=ORIGINAL_MESSAGE,
                              new_string=PARTIAL_MESSAGE), "partial-message"),
        call("read_file", {"file_path": "loader.py"}, "read-loader"),
        ScriptedTurn(content="This final text must not execute after the local limit.", **SIMULATED_USAGE)))


def expert(*, known=True, complete=True):
    usage = SIMULATED_USAGE if known else dict(prompt_tokens=0, completion_tokens=0)
    report = dict(summary="Compare the current field lookup with the public record contract.",
        historical_failure=dict(description="The observed KeyError is wrapped by a RuntimeError.", evidence_ids=["$E0"]),
        current_state=dict(assessment="The current loader source was inspected.", observation_ids=["$O0"]),
        hypotheses=[dict(explanation="The field name may contradict the public features contract.",
            evidence_ids=["$E0"], observation_ids=["$O0"], verification="Run the authorized public check after repair.")],
        recommended_actions=["Re-read current candidate source before any edit."],
        limitations=["Fixed offline fixture; no independent model diagnosis score is asserted."])
    return ModelSpec(turns=(
        ScriptedTurn(calls=(ScriptedCall(call_id="extract", name="extract_log_evidence"),), **usage),
        ScriptedTurn(calls=(ScriptedCall(call_id="read", name="read_project_file",
            arguments_json=json.dumps(dict(path="loader.py"))),), **usage),
        ScriptedTurn(content=json.dumps(report) if complete else "{invalid", **usage)))


def policy(*, model_calls=8, feedback=1, context=32000):
    return ProjectPolicy(task_limits=RuntimeLimits(max_model_calls=model_calls, max_tool_calls=12,
        max_rounds=8, max_context_tokens=context, max_output_tokens=2048, max_total_tokens=200000,
        max_runtime_seconds=45), job_limits=JobLimits(max_model_calls=24, max_tool_calls=60,
        max_total_tokens=400000, max_runtime_seconds=180), max_feedback_rounds=feedback)


def archived(target):
    io = ArtifactIO(target / "artifacts")
    raw = io.read_json(ArtifactRef.from_json((target / "raw-reference.json").read_text()))
    requests, seen = [], set()
    results = list(raw["attempt_results"])
    for consultation in raw["consultations"]:
        if consultation["run"]:
            results.extend(consultation["run"]["results"])
    for result in results:
        for reference in result["outputs"]:
            value = io.read_json(ArtifactRef.from_dict(reference))
            for request in value.get("request_records", []):
                if request["artifact_id"] not in seen:
                    seen.add(request["artifact_id"])
                    requests.append(io.read_json(ArtifactRef.from_dict(request)))
    return raw, io, requests


def assert_integrity(result, raw, io, requests, source, task, checks):
    assert capture_manifest(source) == task.manifest
    for check in checks.values():
        check.check_protected()
    assert SECRET not in json.dumps(requests) and "private_check.py" not in json.dumps(requests)
    assert result["usage_semantics"] == "scripted_fixture_not_provider_usage"
    assert result["actual_prompt_tokens"] is None and result["cost"] is None
    assert result["diagnosis_correct"] is None and result["localization_correct"] is None
    assert not raw["budget"]["pending"]
    assert raw["budget"]["charged"]["model_calls"] == sum(r["budget"]["model_calls"] for r in raw["records"])
    assert result["model_requests"] == len(requests)
    for record in raw["records"]:
        assert record["worker_pid"]
        if record["status"] != "cancelled":
            assert record["worker_exit_code"] == 0
        assert record["job_id"] == raw["job_id"]


@pytest.mark.parametrize("repair, expected", [
    ("none", (False, False, True)), ("correct", (True, True, True)),
    ("public_only", (True, False, True)), ("regression", (True, True, False))])
def test_m4_fixture_health_fault_and_independent_oracle_controls(tmp_path, repair, expected):
    source, task, checks = fixture(tmp_path)
    if repair != "none":
        text = (source / "loader.py").read_text()
        text = text.replace(WRONG, PUBLIC_ONLY if repair == "public_only" else CORRECT)
        if repair == "regression":
            text = text.replace("return value", "return None")
        (source / "loader.py").write_text(text, encoding="utf-8")
    io = ArtifactIO(tmp_path / "oracle-artifacts")
    observations = []
    for profile in ("public", "f2p", "p2p"):
        execution = run_check(checks[profile], source, io, "oracle-fixture", profile)
        assert execution.receipt_error is None, execution.to_dict()
        assert execution.receipt["reported_source_sha256_verified"]
        observations.append(execution.receipt["passed"])
    assert tuple(observations) == expected


@pytest.mark.parametrize("repair, success, f2p, p2p", [
    ("no_patch", False, False, True), ("correct", True, True, True),
    ("public_only", False, False, True), ("regression", False, True, False)])
def test_m4_real_tools_repair_negative_controls_keep_failed_samples(tmp_path, repair, success, f2p, p2p):
    source, task, checks = fixture(tmp_path)
    target = tmp_path / "trial"
    result = ProjectEvaluationRunner().run(target, task, source, checks["public"], checks["f2p"], checks["p2p"],
        writer(repair), policy=policy(feedback=0))
    raw, io, requests = archived(target)
    assert result["end_to_end_success"] is success
    assert result["fail_to_pass"] is f2p and result["pass_to_pass"] is p2p
    assert len(raw["rounds"]) == 1 and not raw["consultations"]
    assert_integrity(result, raw, io, requests, source, task, checks)
    assert recompute(target) == result


def adaptive_trial(tmp_path, *, workers=2, first=None, local_calls=8, handoff=False,
                   known_expert=True, known_writer=True):
    source, task, checks = fixture(tmp_path)
    model = first or writer("no_patch")
    if not known_writer:
        model = replace(model, turns=tuple(replace(t, prompt_tokens=0, completion_tokens=0) for t in model.turns))
    options = {}
    if handoff:
        from researchcoder.evaluation.projects.handoff import HandoffPolicy
        options["handoff_policy"] = HandoffPolicy(mode="local-stop-v1", max_handoffs=1)
    target = tmp_path / "trial"
    # Identical trusted wrapper in both schedules. A short fixed delay makes
    # overlapping real expert lifetimes observable; it is not a speed benchmark.
    wrapper = tmp_path / "observed-expert-worker.py"
    wrapper.write_text("import json,sys,time\nfrom pathlib import Path\n"
        "request=json.loads(Path(sys.argv[1]).read_text())\n"
        "if '.expert-' in request['spec']['task_id']: time.sleep(0.2)\n"
        "from researchcoder.runtime.worker import main\nraise SystemExit(main())\n", encoding="utf-8")
    result = ProjectEvaluationRunner().run(target, task, source, checks["public"], checks["f2p"], checks["p2p"],
        model, policy=policy(model_calls=local_calls), feedback_models=(writer(),),
        expert_policy=ExpertPolicy(mode="public-failure-v1", schedule_version="serial-parallel-v2", max_workers=workers),
        expert_models={"code_analysis": expert(known=known_expert), "log_analysis": expert(known=known_expert)},
        worker_command=(sys.executable, "-B", str(wrapper)), **options)
    raw, io, requests = archived(target)
    assert_integrity(result, raw, io, requests, source, task, checks)
    assert recompute(target) == result
    return result, raw, io, requests, target


def test_m4_two_actual_experts_same_dag_permissions_actions_only_concurrency_differs(tmp_path, monkeypatch):
    from researchcoder.orchestration.scheduler import DAGScheduler
    original = DAGScheduler.execute
    observed = []

    def inspect(self, plan, config, **kwargs):
        normalized = plan.to_dict()
        normalized.pop("job_id")
        profiles = {}
        for name, template in config.templates.items():
            permission = template.spec.policy.to_dict()
            permission["allowed_read_roots"] = ["<same-content-read-only-snapshot>"]
            profiles[name] = dict(role=template.role, policy=permission,
                tools=list(template.config.diagnostic_tools), limits=template.config.limits.to_dict(),
                model=template.config.model.to_dict())
        observed.append(dict(plan=normalized, profiles=profiles, workers=config.max_workers))
        return original(self, plan, config, **kwargs)

    monkeypatch.setattr(DAGScheduler, "execute", inspect)
    runs = []
    for workers in (1, 2):
        root = tmp_path / str(workers)
        root.mkdir()
        result, raw, io, requests, target = adaptive_trial(root, workers=workers)
        assert result["end_to_end_success"] and result["fail_to_pass"] and result["pass_to_pass"]
        assert len(raw["rounds"]) == 2 and len(raw["consultations"]) == 1
        consultation = raw["consultations"][0]
        assert consultation["safe_to_continue"] and consultation["run"]["status"] == "succeeded"
        assert set(consultation["decision"]["roles"]) == {"code_analysis", "log_analysis"}
        records = consultation["records"]
        assert len(records) == 2 and len({r["worker_pid"] for r in records}) == 2
        assert len(raw["records"]) == len(raw["budget"]["settlements"]) == 4
        assert len(consultation["selected_producers"]) == 2
        times = sorted((r["started_ns"], r["ended_ns"]) for r in records)
        if workers == 1:
            assert times[1][0] >= times[0][1]
        else:
            assert max(t[0] for t in times) < min(t[1] for t in times)
        later = json.dumps([r for r in requests if r["task_id"] == "coding-1"])
        assert "candidate_source_paths" in later and "unverified_hypothesis" in later
        assert CORRECT in (target / "candidate/loader.py").read_text()
        assert raw["rounds"][0]["result"]["status"] == "failed"
        runs.append((result, raw))
    assert [v["workers"] for v in observed] == [1, 2]
    assert observed[0]["plan"] == observed[1]["plan"]
    assert observed[0]["profiles"] == observed[1]["profiles"]
    assert all(not task["dependencies"] for task in observed[0]["plan"]["tasks"])
    assert runs[0][0]["model_requests"] == runs[1][0]["model_requests"] == 11
    assert runs[0][1]["budget"]["charged"] == runs[1][1]["budget"]["charged"]


